#!/usr/bin/env -S uv run --with botocore python3
"""
Consolidate the `homelab` R2 bucket's `media/` subtree.

Actions (per the plan generated by this script itself — re-generated on every run):
  - RENAME: `Kasey's Playlists/*` -> `YouTube/Kasey's Playlists/*`
  - DELETE: lowercase `Youtube/*` (case-duplicates of `YouTube/*`) — frees ~48 GB
  - DELETE: `runs/` (drop)
  - KEEP: existing `YouTube/<category>/` trees (Essential, Nice, Study, Wow, Ugh, Gotta...)

Safety:
  - Default mode is DRY-RUN (prints the plan, makes zero writes).
  - Pass --apply to actually mutate.
  - No backup is written. The source data is backed by a Longhorn volume snapshot.
  - Renames are copy-then-delete (server-side copy, no payload transfer).
  - Mutations run in parallel via threads; tune --concurrency to throttle R2 QPS.

Usage:
    # dry-run (default)
    uv run media/yt-dlp/scripts/r2-consolidate.py

    # apply
    uv run media/yt-dlp/scripts/r2-consolidate.py --apply

    # apply with custom parallelism (default 8)
    uv run media/yt-dlp/scripts/r2-consolidate.py --apply --concurrency 16
"""
