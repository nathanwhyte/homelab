# ---------- SigV4 signer (UNSIGNED-PAYLOAD, TLS 1.3) ----------

def sigv4(canonical_query: str) -> tuple[str, str]:
    now = datetime.datetime.now(datetime.timezone.utc)
    amz_date = now.strftime("%Y%m%dT%H%M%SZ")
    date_stamp = amz_date[:8]
    canonical_uri = f"/{BUCKET}"
    canonical_headers = (
        f"host:{HOST}\n"
        f"x-amz-content-sha256:UNSIGNED-PAYLOAD\n"
        f"x-amz-date:{amz_date}\n"
    )
    canonical_request = "\n".join(
        [
            "GET",
            canonical_uri,
            canonical_query,
            canonical_headers,
            "host;x-amz-content-sha256;x-amz-date",
            "UNSIGNED-PAYLOAD",
        ]
    )
    scope = f"{date_stamp}/auto/s3/aws4_request"
    string_to_sign = "\n".join(
        [
            "AWS4-HMAC-SHA256",
            amz_date,
            scope,
            hashlib.sha256(canonical_request.encode()).hexdigest(),
        ]
    )

    def h(k, d):
        return hmac.new(k, d.encode("utf-8"), hashlib.sha256).digest()

    k_date = h(("AWS4" + SK).encode(), date_stamp)
    k_region = h(k_date, "auto")
    k_service = h(k_region, "s3")
    k_signing = h(k_service, "aws4_request")
    sig = hmac.new(k_signing, string_to_sign.encode(), hashlib.sha256).hexdigest()
    return (
        f"AWS4-HMAC-SHA256 Credential={AK}/{scope}, "
        f"SignedHeaders=host;x-amz-content-sha256;x-amz-date, Signature={sig}",
        amz_date,
    )


def canonical_query_string(params: dict[str, str]) -> str:
    """Build the canonical query string.

    S3 SigV4 requires %20 (not '+') for spaces in canonical query strings.
    `urllib.parse.urlencode` defaults to `quote_plus` which is wrong here.
    """
    return "&".join(
        f"{k}={urllib.parse.quote(v, safe='')}" for k, v in sorted(params.items())
    )


def sigv4_for_method(method: str, canonical_uri: str, canonical_query: str) -> tuple[str, str]:
    """Sign a request where the body is UNSIGNED-PAYLOAD.

    PUT/POST/DELETE use the same canonical structure as GET; we share this helper.
    """
    now = datetime.datetime.now(datetime.timezone.utc)
    amz_date = now.strftime("%Y%m%dT%H%M%SZ")
    date_stamp = amz_date[:8]
    canonical_headers = (
        f"host:{HOST}\n"
        f"x-amz-content-sha256:UNSIGNED-PAYLOAD\n"
        f"x-amz-date:{amz_date}\n"
    )
    canonical_request = "\n".join(
        [
            method,
            canonical_uri,
            canonical_query,
            canonical_headers,
            "host;x-amz-content-sha256;x-amz-date",
            "UNSIGNED-PAYLOAD",
        ]
    )
    scope = f"{date_stamp}/auto/s3/aws4_request"
    string_to_sign = "\n".join(
        [
            "AWS4-HMAC-SHA256",
            amz_date,
            scope,
            hashlib.sha256(canonical_request.encode()).hexdigest(),
        ]
    )

    def h(k, d):
        return hmac.new(k, d.encode("utf-8"), hashlib.sha256).digest()

    k_date = h(("AWS4" + SK).encode(), date_stamp)
    k_region = h(k_date, "auto")
    k_service = h(k_region, "s3")
    k_signing = h(k_service, "aws4_request")
    sig = hmac.new(k_signing, string_to_sign.encode(), hashlib.sha256).hexdigest()
    return (
        f"AWS4-HMAC-SHA256 Credential={AK}/{scope}, "
        f"SignedHeaders=host;x-amz-content-sha256;x-amz-date, Signature={sig}",
        amz_date,
    )


# ---------- request helpers ----------

# Global rate limiter: at most N requests per second across all threads.
# R2's SigV4 signing timestamp has 1-second resolution, so back-to-back
# requests can collide. We pace them out, but allow parallelism.
_RPS = 32  # ~32 req/s aggregate; safe headroom under R2's per-key limits
_TOKEN_LOCK = threading.Lock()
_TOKENS = _RPS
_LAST = time.monotonic()


def _take_token():
    global _TOKENS, _LAST
    while True:
        with _TOKEN_LOCK:
            now = time.monotonic()
            elapsed = now - _LAST
            _TOKENS = min(_RPS, _TOKENS + elapsed * _RPS)
            _LAST = now
            if _TOKENS >= 1:
                _TOKENS -= 1
                return
        # No token; sleep briefly and retry.
        time.sleep(1.0 / _RPS)


def request(method: str, key: str, params: dict[str, str] | None = None):
    """Issue a signed R2 request. `key` is the object key (not URL-encoded)."""
    _take_token()
    params = params or {}
    canonical_query = canonical_query_string(params)
    canonical_uri = "/" + urllib.parse.quote(BUCKET, safe="") + "/" + urllib.parse.quote(key, safe="")
    auth, amz_date = sigv4_for_method(method, canonical_uri, canonical_query)
    url = f"https://{HOST}{canonical_uri}"
    if canonical_query:
        url += "?" + canonical_query
    req = urllib.request.Request(
        url,
        headers={
            "Authorization": auth,
            "x-amz-date": amz_date,
            "x-amz-content-sha256": "UNSIGNED-PAYLOAD",
            "Host": HOST,
        },
        method=method,
    )
    return urllib.request.urlopen(req)


def list_v2(prefix: str, with_delim: bool = False, continuation_token: str | None = None):
    params: dict[str, str] = {"list-type": "2", "max-keys": "1000"}
    if with_delim:
        params["delimiter"] = "/"
    if prefix:
        params["prefix"] = prefix
    if continuation_token:
        params["continuation-token"] = continuation_token
    with request("GET", "", params) as r:
        return ET.fromstring(r.read().decode())


def drain_keys(prefix: str) -> list[tuple[str, int]]:
    """Paged to completion. Returns list of (key, size)."""
    out: list[tuple[str, int]] = []
    token = None
    while True:
        root = list_v2(prefix, with_delim=False, continuation_token=token)
        for c in root.findall("s3:Contents", NS):
            out.append(
                (
                    c.find("s3:Key", NS).text,
                    int(c.find("s3:Size", NS).text),
                )
            )
        if root.get("IsTruncated") == "true":
            token = root.get("NextContinuationToken")
        else:
            return out


# ---------- mutation helpers ----------

def copy_object(src_key: str, dst_key: str) -> int:
    """Server-side copy. Returns the HTTP status code."""
    _take_token()
    # The copy source is sent in the x-amz-copy-source header (URL-encoded key).
    # The destination key is part of the request URL.
    params: dict[str, str] = {}
    canonical_query = canonical_query_string(params)
    canonical_uri = "/" + urllib.parse.quote(BUCKET, safe="") + "/" + urllib.parse.quote(dst_key, safe="")
    auth, amz_date = sigv4_for_method("PUT", canonical_uri, canonical_query)
    url = f"https://{HOST}{canonical_uri}"
    if canonical_query:
        url += "?" + canonical_query
    copy_source = f"/{BUCKET}/{urllib.parse.quote(src_key, safe='')}"
    req = urllib.request.Request(
        url,
        headers={
            "Authorization": auth,
            "x-amz-date": amz_date,
            "x-amz-content-sha256": "UNSIGNED-PAYLOAD",
            "Host": HOST,
            "x-amz-copy-source": copy_source,
        },
        method="PUT",
    )
    with urllib.request.urlopen(req) as r:
        return r.status


