# ---------- plan ----------

# (source_prefix, target_relative_under_NEW_BASE | None, action)
SOURCES = [
    (OLD_BASE + "YouTube/Essential/",                  "Essential/", "KEEP"),
    (OLD_BASE + "YouTube/Gotta Keep These Somewhere/", "Gotta Keep These Somewhere/", "KEEP"),
    (OLD_BASE + "YouTube/Nice/",                       "Nice/", "KEEP"),
    (OLD_BASE + "YouTube/Study/",                      "Study/", "KEEP"),
    (OLD_BASE + "YouTube/Ugh/",                        "Ugh/", "KEEP"),
    (OLD_BASE + "YouTube/Wow/",                        "Wow/", "KEEP"),
    (OLD_BASE + "Kasey's Playlists/",                  "Kasey's Playlists/", "RENAME"),
    (OLD_BASE + "Youtube/Essential/",                  None, "DELETE"),
    (OLD_BASE + "Youtube/Gotta Keep These Somewhere/", None, "DELETE"),
    (OLD_BASE + "Youtube/Nice/",                       None, "DELETE"),
    (OLD_BASE + "Youtube/Study/",                      None, "DELETE"),
    (OLD_BASE + "runs/",                               None, "DELETE"),
]


def build_plan() -> list[dict]:
    plan: list[dict] = []
    for source, target_rel, action in SOURCES:
        for key, size in drain_keys(source):
            if action == "KEEP":
                plan.append({"action": "KEEP", "src": key, "dst": key, "size": size})
            elif action == "RENAME":
                dst = NEW_BASE + target_rel + key[len(source):]
                plan.append({"action": "RENAME", "src": key, "dst": dst, "size": size})
            elif action == "DELETE":
                plan.append({"action": "DELETE", "src": key, "dst": None, "size": size})
    return plan


def print_plan(plan: list[dict]) -> None:
    by_action: dict[str, list[dict]] = defaultdict(list)
    for p in plan:
        by_action[p["action"]].append(p)
    print("=" * 80)
    print("R2 MEDIA CONSOLIDATION PLAN")
    print("=" * 80)
    for action in ("KEEP", "RENAME", "DELETE"):
        items = by_action[action]
        if not items:
            continue
        total = sum(p["size"] for p in items)
        print(f"\n{action}: {len(items)} objects, {total/1e9:.3f} GB")
        for p in items[:3]:
            if p["action"] == "DELETE":
                print(f"  {p['src']}  ({p['size']/1e6:.1f} MB)")
            else:
                print(f"  {p['src']}\n    -> {p['dst']}")
        if len(items) > 3:
            print(f"  ... and {len(items) - 3} more")
    print()


def apply_plan(plan: list[dict], concurrency: int) -> None:
    """Two-phase: RENAME first (copy + delete-source), DELETE second.

    For each RENAME, we copy the source to the destination, then delete the source.
    This is not transactional — if any step fails, we stop and surface the error.
    Mutations are parallelised across `concurrency` threads.
    """
    renames = [p for p in plan if p["action"] == "RENAME"]
    deletes = [p for p in plan if p["action"] == "DELETE"]

    rename_lock = threading.Lock()
    rename_done = [0]

    def do_rename(p: dict):
        # Server-side copy (no payload transfer) to the destination.
        status = copy_object(p["src"], p["dst"])
        if status != 200:
            raise RuntimeError(f"copy failed: {p['src']} -> {p['dst']} (HTTP {status})")
        # Then delete the source.
        status = delete_object(p["src"])
        if status not in (202, 204):
            raise RuntimeError(f"delete-after-copy failed: {p['src']} (HTTP {status})")
        with rename_lock:
            rename_done[0] += 1
            done = rename_done[0]
        if done % 100 == 0 or done == len(renames):
            print(f"  [rename {done}/{len(renames)}]", flush=True)

    print(f"Phase 1: RENAME  ({len(renames)} objects, concurrency={concurrency})")
    run_parallel(do_rename, renames, concurrency)

    delete_lock = threading.Lock()
    delete_done = [0]

    def do_delete(p: dict):
        status = delete_object(p["src"])
        if status not in (202, 204):
            raise RuntimeError(f"delete failed: {p['src']} (HTTP {status})")
        with delete_lock:
            delete_done[0] += 1
            done = delete_done[0]
        if done % 100 == 0 or done == len(deletes):
            print(f"  [delete {done}/{len(deletes)}]", flush=True)

    print(f"\nPhase 2: DELETE  ({len(deletes)} objects, concurrency={concurrency})")
    run_parallel(do_delete, deletes, concurrency)

    print("\nAll operations succeeded.")


def run_parallel(fn, items, concurrency):
    """Run `fn(item)` over `items` in parallel; raise on first exception."""
    if not items:
        return
    with concurrent.futures.ThreadPoolExecutor(max_workers=concurrency) as ex:
        futs = [ex.submit(fn, p) for p in items]
        # as_completed yields in completion order; surface the first failure.
        for fut in concurrent.futures.as_completed(futs):
            exc = fut.exception()
            if exc is not None:
                # Best-effort cancel siblings; they're either pending or running.
                for f in futs:
                    f.cancel()
                raise exc


def verify_post_state() -> None:
    """Spot-check the post-state: each target prefix should still resolve."""
    print("\nPost-state verification:")
    for source, target_rel, action in SOURCES:
        if action == "KEEP":
            keys = drain_keys(source)
            print(f"  KEEP   {source}  ->  {len(keys)} objects")
        elif action == "RENAME":
            dst_prefix = NEW_BASE + target_rel
            keys = drain_keys(dst_prefix)
            print(f"  RENAMED -> {dst_prefix}  ->  {len(keys)} objects")
            # Source prefix should now be empty.
            leftover = drain_keys(source)
            if leftover:
                print(f"  WARNING: source still has {len(leftover)} objects: {source}")
        elif action == "DELETE":
            leftover = drain_keys(source)
            if leftover:
                print(f"  DELETE {source}  ->  STILL HAS {len(leftover)} objects!  (FAIL)")
            else:
                print(f"  DELETE {source}  ->  empty  (OK)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true", help="Actually mutate. Default is dry-run.")
    ap.add_argument(
        "--concurrency",
        type=int,
        default=8,
        help="Worker threads for mutations (default 8). 16-32 is fine for R2; >32 risks 429s.",
    )
    args = ap.parse_args()

    print("Building plan (re-enumerating all source prefixes)...")
    plan = build_plan()
    print_plan(plan)

    if not args.apply:
        print("DRY-RUN. Pass --apply to execute.")
        sys.exit(0)

    print("=" * 80)
    print("APPLYING PLAN")
    print("=" * 80)
    apply_plan(plan, concurrency=args.concurrency)
    verify_post_state()


if __name__ == "__main__":
    main()
